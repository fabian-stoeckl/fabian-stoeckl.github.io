const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--no-zygote','--single-process']});
 const context=await browser.newContext(),page=await context.newPage(),errors=[],requests=[];
 page.on('pageerror',e=>errors.push(e.message));
 let failure=false;
 await context.route('**/repos/fabian-stoeckl/morgenzeitung-feedback**',route=>{
   const req=route.request(),url=new URL(req.url()),method=req.method();
   const headers={'access-control-allow-origin':'*','access-control-allow-methods':'GET, POST, PATCH, OPTIONS',
     'access-control-allow-headers':'authorization, content-type, x-github-api-version, accept'};
   if(method==='OPTIONS')return route.fulfill({status:204,headers});
   requests.push({path:url.pathname,method,headers:req.headers(),body:req.postDataJSON?.()});
   assert.equal(req.headers().authorization,'Bearer github_pat_BROWSER_TEST_123456789');
   if(failure)return route.fulfill({status:503,headers,json:{message:'server unavailable'}});
   if(method==='GET')return route.fulfill({headers,json:{private:true,full_name:'fabian-stoeckl/morgenzeitung-feedback'}});
   if(method==='POST'||method==='PATCH')return route.fulfill({headers,json:{number:23,html_url:'https://github.com/fabian-stoeckl/morgenzeitung-feedback/issues/23'}});
   throw Error('Unexpected GitHub API '+method);
 });
 await page.goto('http://127.0.0.1:8765/Privat/Pressespiegel/');
 await page.waitForSelector('article');
 assert.equal(await page.locator('#overview-list li').count(),3);
 assert.equal(await page.locator('article').count(),5);
 assert(await page.locator('#github-setup').isVisible());
 await page.locator('article').first().getByLabel('Sehr relevant',{exact:true}).check();
 await page.locator('article').first().locator('textarea').fill('Mehr Zahlen');
 await page.locator('#feedback').fill('Mehr Handelsblatt');
 await page.locator('#feedback-form button[type=submit]').click();
 assert.match(await page.locator('#feedback-status').innerText(),/einmalig/);
 assert.equal(requests.length,0);
 await page.locator('#github-token').fill('github_pat_BROWSER_TEST_123456789');
 await page.locator('#remember-token').check();
 await page.locator('#github-setup-form button[type=submit]').click();
 await page.waitForFunction(()=>document.querySelector('#github-connected')?.hidden===false);
 assert(await page.locator('#github-setup').isHidden());
 assert.equal(requests[0].method,'GET');
 await page.locator('#feedback-form button[type=submit]').click();
 await page.waitForFunction(()=>{const t=document.querySelector('#feedback-status').textContent;return t.includes('Erfolgreich')||t.includes('Nicht bestätigte')||t.includes('bereits gespeichert')||t.includes('aktualisiert');},{timeout:10000});
 console.log('GitHub POST status:',await page.locator('#feedback-status').innerText());
 console.log('Intercepted API requests:',requests.map(r=>r.method+' '+r.path).join(' / '));
 assert.match(await page.locator('#feedback-status').innerText(),/Erfolgreich/);
 const post=requests.find(r=>r.method==='POST');
 assert(post);
 assert.match(post.body.body,/Mehr Zahlen/);
 assert.match(post.body.body,/Mehr Handelsblatt/);
 assert.equal(post.path,'/repos/fabian-stoeckl/morgenzeitung-feedback/issues');
 assert.match(await page.locator('#feedback-issue-link').getAttribute('href'),/issues\/23/);
 await page.locator('#feedback-form button[type=submit]').click();
 await page.waitForFunction(()=>document.querySelector('#feedback-status').textContent.includes('Bereits'));
 assert.equal(requests.filter(r=>r.method==='POST').length,1);
 await page.locator('#feedback').fill('Mehr KI und Industrie');
 await page.locator('#feedback-form button[type=submit]').click();
 await page.waitForFunction(()=>document.querySelector('#feedback-status').textContent.includes('aktualisiert'));
 assert.equal(requests.filter(r=>r.method==='PATCH').length,1);
 assert(requests.find(r=>r.method==='PATCH').path.endsWith('/issues/23'));
 failure=true;
 await page.locator('#feedback').fill('Mehr zum Strommarkt');
 await page.locator('#feedback-form button[type=submit]').click();
 await page.waitForFunction(()=>document.querySelector('#feedback-status').textContent.includes('nicht speichern'));
 assert.equal(await page.locator('#feedback').inputValue(),'Mehr zum Strommarkt');
 assert.equal(await page.locator('#feedback-confirmation').isHidden(),true);
 failure=false;
 await page.reload();
 await page.waitForSelector('article');
 assert(await page.locator('#github-connected').isVisible());
 for(const width of [1440,390]){
   await page.setViewportSize({width,height:1000});
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
   await page.screenshot({path:'artifacts/screenshots/morgenzeitung-direct-'+width+'.png',fullPage:true});
 }
 await page.locator('#github-disconnect').click();
 assert(await page.locator('#github-setup').isVisible());
 assert.equal(await page.evaluate(()=>localStorage.getItem('morgenzeitung:github-token:v1')),null);
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('Direct browser GitHub API save, update, duplicate, failure, persistence, disconnect, responsive preview passed.');
})().catch(e=>{console.error(e);process.exit(1)});
