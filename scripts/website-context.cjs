'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
function registry(root) {
  const dir = path.join(root, 'docs/website-context');
  const names = new Set(), paths = new Set();
  const areas = fs.readdirSync(dir).filter(f => f.endsWith('.md') && f !== 'README.md').sort().map(file => {
    assert.match(file, /^[A-Za-z0-9_-]+\.md$/, `Unsafe protocol filename: ${file}`);
    const body = fs.readFileSync(path.join(dir, file), 'utf8');
    const matches = [...body.matchAll(/<!-- website-area: (.*?) -->/g)];
    assert.equal(matches.length, 1, `${file}: exactly one metadata comment required`);
    const meta = JSON.parse(matches[0][1]);
    assert.ok(typeof meta.name === 'string' && meta.name.trim() && !/[|\r\n<>]/.test(meta.name), `${file}: invalid name`);
    assert.ok(!names.has(meta.name), `Duplicate area: ${meta.name}`); names.add(meta.name);
    assert.ok(Array.isArray(meta.paths), `${file}: paths must be an array`);
    for (const p of meta.paths) {
      assert.ok(typeof p === 'string' && /^(?:[A-Za-z0-9_.-]+\/)*[A-Za-z0-9_.-]+\/?$/.test(p) && !p.split('/').some(x => x === '.' || x === '..'), `${file}: unsafe source path`);
      assert.ok(!paths.has(p), `Duplicate source path: ${p}`); paths.add(p);
      assert.ok(fs.existsSync(path.join(root, p)), `${file}: missing source ${p}`);
    }
    assert.match(body, /^# .+/m, `${file}: missing heading`);
    assert.match(body, /\*\*Stand:\*\*\s+\d{2}\.\d{2}\.\d{4}/, `${file}: missing dated status`);
    assert.match(body, /^## .*Offen/im, `${file}: missing open-items section`);
    return {file, ...meta};
  });
  assert.ok(areas.length, 'No area protocols');
  const pages = ['index.md'];
  function walk(dir) { if (!fs.existsSync(path.join(root, dir))) return; for (const e of fs.readdirSync(path.join(root, dir), {withFileTypes:true})) { const p = dir + '/' + e.name; if(e.isDirectory()) walk(p); else if(e.name === 'index.html') pages.push(p); } }
  walk('Privat');
  // Keep only explicit one-page redirects for real historic bookmarks.
  // They are not a second registered newspaper or an editable website area.
  const legacyRedirects = {
    'Privat/Morgenzeitung-3/index.html': '/Privat/Persoenliche-Zeitung/',
    'Privat/Morgenzeitung-3/praeferenzen.html': '/Privat/Persoenliche-Zeitung/praeferenzen.html',
    'Privat/Morgenzeitung-3/lern-ausgabe-2026-10-28/index.html': '/Privat/Persoenliche-Zeitung/lern-ausgabe-2026-10-28/'
  };
  for (const p of pages) {
    if ([...paths].some(s => s.endsWith('/') ? p.startsWith(s) : p === s)) continue;
    const dest = legacyRedirects[p];
    if (dest && paths.has('Privat/Persoenliche-Zeitung/')) {
      const html = fs.readFileSync(path.join(root,p),'utf8');
      assert.ok(html.includes('location.replace(') && html.includes(dest),
        `Legacy bookmark must redirect to the registered newspaper: ${p}`);
      continue;
    }
    assert.fail(`Unregistered website page: ${p}`);
  }
  assert.match(fs.readFileSync(path.join(root, '_config.yml'), 'utf8'), /^\s+- docs\s*$/m, 'docs must be excluded from Jekyll');
  assert.match(fs.readFileSync(path.join(root, 'AGENTS.md'), 'utf8'), /docs\/website-context\/README\.md/, 'AGENTS must link registry');
  return areas;
}
function render(areas) {
  return '# Website-Bereichsprotokolle\n\nVerbindliche Bereichshistorie für `fabian-stoeckl/fabian-stoeckl.github.io`. Der bestehende Skill „Fabians Website ändern“ steuert den Ablauf und lädt dieses Verzeichnis und das gewählte Protokoll frisch aus GitHub.\n\n<!-- Generated by npm run context:update; do not edit by hand. -->\n\n## Bereiche\n\n| Bereich | Protokoll | Quelldateien / Verzeichnisse |\n| --- | --- | --- |\n' + areas.map(a => `| ${a.name} | [${a.file}](${a.file}) | ${a.paths.length ? a.paths.map(p => '`'+p+'`').join(', ') : 'Geplant; noch keine Website-Dateien'} |`).join('\n') + '\n\n„Neuer Bereich“ wird im Skill zusätzlich angeboten. Neues Protokoll mit Metadaten anlegen, dann `npm run context:update` und `npm run check:context` ausführen. Die Auswahl ergibt sich aus dieser Tabelle; keine feste Bereichsliste im Skill oder Test.\n\n## Zuständigkeiten\n\n- Skill: Bearbeitungsablauf, Freigabe und Veröffentlichung.\n- AGENTS.md und DEVELOPMENT.md: technische Regeln und Testbefehle.\n- Bereichsprotokolle: datierter Stand, bestätigte Entscheidungen, Verlauf und offene Punkte.\n- Dieses Verzeichnis: automatisch aus den Protokollen erzeugte Auswahl.\n\n`docs/` ist vom Website-Build ausgeschlossen, bleibt aber im öffentlichen GitHub-Repository lesbar. Keine Geheimnisse oder privaten Chatvolltexte eintragen.\n';
}
function run(root, write=false) { const areas=registry(root); const expected=render(areas); const target=path.join(root,'docs/website-context/README.md'); if(write) fs.writeFileSync(target,expected); else assert.equal(fs.readFileSync(target,'utf8'),expected,'Registry outdated: run npm run context:update'); return areas; }
module.exports={registry,render,run};
if(require.main===module) { const areas=run(path.resolve(__dirname,'..'),process.argv.includes('--write')); console.log(`PASS: ${areas.length} areas, registry and website coverage consistent`); }
