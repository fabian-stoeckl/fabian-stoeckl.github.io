"""Auditable per-publisher access monitoring; never confuse RSS with fulltext.

The scheduled GitHub-runner smoke proves only feed reachability and a sample
article's identity. True three-day publisher blackout warnings require
SEPARATE completed editorial research ledgers, never just a blocked feed.
These immutable private ledgers are generated by the daily S3/S4 researcher.
"""
import argparse
import datetime as dt
import json
from pathlib import Path
from zoneinfo import ZoneInfo

from scripts.morgenzeitung_official_feeds import FEEDS

REQUIRED_SOURCES = (
    "ORF", "Der Standard", "Die Presse", "Kronen Zeitung",
    "Handelsblatt", "FAZ", "Süddeutsche Zeitung", "DIE ZEIT",
    "DER SPIEGEL", "BILD", "WirtschaftsWoche",
    "Financial Times", "The New York Times", "The Washington Post",
    "The Guardian", "NZZ", "Reuters", "Associated Press",
    "Bloomberg", "Euronews", "BBC News", "POLITICO Europe",
)
ALLOWED_OUTCOMES = {"VERIFIED_ARTICLES", "NO_SUITABLE_ARTICLES",
                    "NO_VERIFIABLE_ARTICLES", "NOT_CHECKED"}
VERIFICATION_METHODS = {"direct_original", "official_publisher_feed",
                        "publisher_metadata", "independent_index"}
EVIDENCE_GATES = {"direct_original", "official_publisher_feed",
                  "publisher_metadata"}


def _date(day):
    if not isinstance(day, str):
        raise ValueError("Date required")
    try:
        parsed = dt.date.fromisoformat(day)
    except ValueError as exc:
        raise ValueError("Invalid ISO date") from exc
    if parsed.isoformat() != day:
        raise ValueError("Noncanonical date")
    return parsed


def feed_health(smoke, day, *, run_id=None):
    """Describe every obligatory source even if no first-party feed exists."""
    _date(day)
    if not isinstance(smoke, dict) or smoke.get("report_type") != "real_publisher_first_party_feed_smoke":
        raise ValueError("Actual GitHub runner publisher-feed smoke required")
    entries = smoke.get("results")
    if not isinstance(entries, list) or len(entries) != len(FEEDS):
        raise ValueError("Smoke does not cover all configured feed publishers")
    by_source = {r.get("publisher"): r for r in entries if isinstance(r, dict)}
    if len(by_source) != len(FEEDS) or set(by_source) != set(FEEDS):
        raise ValueError("Missing, duplicate or unknown publisher")
    rows = []
    for name in REQUIRED_SOURCES:
        row = by_source.get(name)
        if row is None:
            status = "NO_OFFICIAL_FEED_CONFIGURED"
            items = None
            feed = None
        else:
            if row.get("identity_status") == "LIVE_IDENTITY_MATCH" and row.get("status") == "FEED_READABLE":
                status = "ORIGINAL_IDENTITY_MATCH"
            elif row.get("status") == "FEED_READABLE":
                status = "FEED_READABLE_IDENTITY_UNPROVEN"
            elif row.get("status") == "EMPTY_FEED":
                status = "FEED_EMPTY"
            else:
                status = "FEED_ACCESS_INCONCLUSIVE"
            items = row.get("items", 0)
            feed = row.get("working_feed")
        rows.append({
            "publisher": name, "feed_status": status, "feed_items": items,
            "working_official_feed": feed,
            "official_feed_sample_article_identity_confirmed": status == "ORIGINAL_IDENTITY_MATCH",
            # A feed does not prove direct access or the completeness of research.
            "fulltext_available": None,
            "editorial_research_confirmed": False,
            "edition_selected_articles": None,
        })
    return {
        "schema": 1, "report_type": "source_feed_health",
        "date": day, "run_id": run_id, "publishers": rows,
        "publisher_count": len(rows),
        "feed_adapters": len(FEEDS),
        "live_identity_sample_confirmed": sum(
            x["feed_status"] == "ORIGINAL_IDENTITY_MATCH" for x in rows),
        "scope": "Feed identity diagnostics only. Never imply publisher editorial availability or fulltext.",
    }


def validate_editorial_report(report):
    """Require an actual S3/S4 ledger for ALL mandatory sources.

    An inaccessible publisher may be reported only after multiple documented
    research routes. 'Zero selected articles' is NOT a network-access failure.
    """
    if not isinstance(report, dict) or report.get("report_type") != "source_editorial_research":
        raise ValueError("Editorial research ledger required")
    _date(report.get("date"))
    if report.get("research_complete") is not True:
        raise ValueError("Partial research ledger cannot prove all-source coverage")
    records = report.get("publishers")
    if not isinstance(records, list) or len(records) != len(REQUIRED_SOURCES):
        raise ValueError("Missing mandatory publisher research records")
    by_source = {}
    for row in records:
        if not isinstance(row, dict):
            raise ValueError("Invalid publisher record")
        name = row.get("publisher")
        if name not in REQUIRED_SOURCES or name in by_source:
            raise ValueError("Unknown or duplicate publisher")
        by_source[name] = row
        outcome = row.get("outcome")
        if outcome not in ALLOWED_OUTCOMES:
            raise ValueError("Invalid editorial source outcome")
        n = row.get("verified_original_count")
        if type(n) is not int or n < 0:
            raise ValueError("Invalid independently verified count")
        if outcome == "VERIFIED_ARTICLES" and n < 1:
            raise ValueError("Must supply confirmed original count")
        if outcome == "NO_SUITABLE_ARTICLES" and n < 1:
            raise ValueError("No-suitable-articles requires independently verified originals; otherwise report NO_VERIFIABLE_ARTICLES")
        if outcome == "NO_VERIFIABLE_ARTICLES" and n:
            raise ValueError("Negative outcomes contradict verified originals")
        methods = row.get("attempted_methods")
        if not isinstance(methods, list) or any(x not in VERIFICATION_METHODS for x in methods):
            raise ValueError("Invalid research methods")
        if outcome == "NOT_CHECKED":
            raise ValueError("Complete editorial report may not leave publishers unexamined")
        if outcome == "NO_VERIFIABLE_ARTICLES":
            # Explicitly require searching originals AND an independent route,
            # plus contemporaneous immutable references. It may still be
            # incomplete if all those methods fail, never an implicit outage.
            if "direct_original" not in methods or not EVIDENCE_GATES.intersection(
                    set(methods) - {"direct_original"}) and not (
                    report.get("research_policy") == "no-link-tests"
                    and "direct_original" in methods and "independent_index" in methods):
                raise ValueError("Blocked claim lacks independent alternative attempt")
            evidence = row.get("attempt_evidence")
            if (not isinstance(evidence, list) or len(evidence) < 2
                    or not all(isinstance(x, str) and x.strip() for x in evidence)):
                raise ValueError("Blocked claim lacks traceable research evidence")
    if set(by_source) != set(REQUIRED_SOURCES):
        raise ValueError("Incomplete editorial source inventory")
    return by_source


def multi_day_alerts(day, editorial_reports):
    """Only issue a *publisher blackout* after 3 independently recorded days.

    Absent source ledgers are flagged as audit gaps, not mistaken for outages.
    An isolated 403 or an empty feed can NEVER meet this criterion.
    """
    today = _date(day)
    by_day = {}
    for report in editorial_reports:
        if not isinstance(report, dict):
            raise ValueError("Invalid history")
        target = _date(report.get("date"))
        if target > today:
            raise ValueError("Future editorial report")
        if target in by_day:
            raise ValueError("Duplicate daily research ledgers must be version-resolved first")
        by_day[target] = validate_editorial_report(report)
    required_days = [today - dt.timedelta(days=k) for k in (2, 1, 0)]
    missing = [d.isoformat() for d in required_days if d not in by_day]
    if missing:
        return {"date": day, "verdict": "AUDIT_GAP", "missing_dates": missing,
                "confirmed_blackouts": [], "note": "No publisher blackout can be proved without three complete editorial ledgers"}
    problems = []
    for name in REQUIRED_SOURCES:
        records = [by_day[d][name] for d in required_days]
        if all(x["outcome"] == "NO_VERIFIABLE_ARTICLES"
               and x["verified_original_count"] == 0 for x in records):
            problems.append({"publisher": name, "status": "CONFIRMED_RESEARCH_ACCESS_GAP",
                             "dates": [d.isoformat() for d in required_days],
                             "warning": "Three research days without verifiable publisher originals despite documented direct and alternate checks"})
    return {"date": day, "verdict": "ACCESS_GAPS" if problems else "NO_CONFIRMED_ACCESS_GAPS",
            "confirmed_blackouts": problems, "missing_dates": [],
            "note": "Do not infer a blackout from zero publication selections or blocked fulltexts when metadata is verifiable"}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--smoke", type=Path, required=True)
    p.add_argument("--date", required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--run-id", default=None)
    args = p.parse_args()
    report = feed_health(json.loads(args.smoke.read_text()), args.date,
                         run_id=args.run_id)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2)+"\n")
    print(json.dumps({"date": report["date"],
                      "publishers": report["publisher_count"],
                      "configured_feeds": report["feed_adapters"],
                      "identity_verified": report["live_identity_sample_confirmed"],
                      "note": report["scope"]}, ensure_ascii=False))


if __name__ == "__main__":
    main()
